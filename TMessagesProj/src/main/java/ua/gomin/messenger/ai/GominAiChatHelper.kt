     * Використовує retry logic для транзієнтних помилок (429, 503, timeout).
     */
    fun analyzeManipulation(
        partnerName: String,
        historyText: String,
        callback: (success: Boolean, resultText: String) -> Unit
    ) {
        val apiKey = GominGeminiConfig.getApiKey()
        val modelName = GominGeminiConfig.getModelName().ifEmpty { "gemini-2.5-flash" }

        if (TextUtils.isEmpty(apiKey)) {
            callback(false, "Бро, спочатку введи свій API-ключ у налаштуваннях! ⚙️")
            return
        }

        val configBuilder = GenerationConfig.Builder().apply {
            temperature = 0.2f
            maxOutputTokens = 8192
        }

        val safetySettings = arrayListOf(
            SafetySetting(HarmCategory.HARASSMENT, BlockThreshold.NONE),
            SafetySetting(HarmCategory.HATE_SPEECH, BlockThreshold.NONE),
            SafetySetting(HarmCategory.SEXUALLY_EXPLICIT, BlockThreshold.NONE),
            SafetySetting(HarmCategory.DANGEROUS_CONTENT, BlockThreshold.NONE)
        )

        val model = GenerativeModel(
            modelName,
            apiKey,
            configBuilder.build(),
            safetySettings
        )

        val modelFutures = GenerativeModelFutures.from(model)

        val promptContent = Content.Builder().apply {
            role = "user"
            text("Системна інструкція: ${shieldSystemPrompt}\n\nПроаналізуй наступну історію діалогу з ${partnerName}:\n${historyText}")
        }.build()

        sendWithRetry(modelFutures, promptContent, 0, callback)
    }

    /**
     * Надсилає запит з retry logic. Retry при транзієнтних помилках (429, 503, timeout, network).
     */
    // Поточний API запит — щоб можна було скасувати при dismiss
    @Volatile
    private var currentFuture: ListenableFuture<*>? = null

    fun cancelCurrentRequest() {
        currentFuture?.cancel(true)
        currentFuture = null
    }

    private fun sendWithRetry(
        modelFutures: GenerativeModelFutures,
        promptContent: Content,
        attempt: Int,
        callback: (success: Boolean, resultText: String) -> Unit
    ) {
        val responseFuture = modelFutures.generateContent(promptContent)
        currentFuture = responseFuture
        val executor = ContextCompat.getMainExecutor(ApplicationLoader.applicationContext)

        Futures.addCallback(responseFuture, object : FutureCallback<com.google.ai.client.generativeai.type.GenerateContentResponse> {
            override fun onSuccess(result: com.google.ai.client.generativeai.type.GenerateContentResponse?) {
                val replyText = result?.text?.trim() ?: "Модель повернула порожній аналіз."
                AndroidUtilities.runOnUIThread {
                    callback(true, replyText)
                }
            }

            override fun onFailure(t: Throwable) {
                FileLog.e(t)
                val errorMessage = t.message ?: "Невідома помилка мережі."
                val isRetryable = errorMessage.contains("429") ||
                    errorMessage.contains("503") ||
                    errorMessage.contains("UNAVAILABLE") ||
                    errorMessage.contains("deadline") ||
                    errorMessage.contains("timeout", ignoreCase = true)

                if (isRetryable && attempt < MAX_RETRIES) {
                    val delay = RETRY_DELAY_MS * (attempt + 1)
                    retryExecutor.schedule({
                        sendWithRetry(modelFutures, promptContent, attempt + 1, callback)
                    }, delay, java.util.concurrent.TimeUnit.MILLISECONDS)
                } else {
                    AndroidUtilities.runOnUIThread {
                        callback(false, "Помилка аналізу ШІ: ${errorMessage}\n\nМожливо, Gemini перевантажений (код 429). Спробуй ще раз трохи пізніше! ☕")
                    }
                }
            }
        }, executor)
    }

    private fun getPrefs() = ApplicationLoader.applicationContext.getSharedPreferences("gomin_shield_cache", android.content.Context.MODE_PRIVATE)

    fun getCachedResult(dialogId: Long): String? {
        return getPrefs().getString("shield_result_$dialogId", null)
    }

    fun getCachedHistory(dialogId: Long): String? {
        return getPrefs().getString("shield_history_$dialogId", null)
    }

    fun saveToCache(dialogId: Long, result: String, history: String) {
        getPrefs().edit()
            .putString("shield_result_$dialogId", result)
            .putString("shield_history_$dialogId", history)
            .apply()
    }
